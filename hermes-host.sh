EOF
  chown "root:$HERMES_GID" "$tmp"; chmod 640 "$tmp"; mv -f "$tmp" "$AGENT_ENV"
}

write_provenance() {
  local sha="$1" version
  version="$(sed -n 's/^version = "\(.*\)"/\1/p' "$HERMES_RELEASES/${sha:0:12}/pyproject.toml" | head -n1)"
  printf '{"deployment_kind":"image","image":"host:%s","manager":"command-center","revision":"%s","schema":1,"version":"%s"}\n' \
    "$HERMES_RELEASES" "$sha" "${version:-unknown}" > "$PROVENANCE.tmp"
  chmod 444 "$PROVENANCE.tmp"; mv -f "$PROVENANCE.tmp" "$PROVENANCE"
}

# hermes-gateway.service = what Hermes itself generates for a system unit (so `hermes gateway …`
# sees it as current), our settings in a drop-in (EnvironmentFile wins over its Environment=).
write_units() {
  local mem="${AGENT_MEM_LIMIT^^}"
  [ -e "$HERMES_CURRENT/.release" ] || die "no active release: sudo $0 build && sudo $0 activate <sha12>"
  env -i HOME=/root PATH="$(agent_path)" HERMES_HOME=/opt/data "$HERMES_CURRENT/.venv/bin/python" -c \
    'import sys; from hermes_cli.gateway_service_unit import generate_systemd_unit; sys.stdout.write(generate_systemd_unit(system=True, run_as_user=sys.argv[1]))' \
    "$OP_USER" > /etc/systemd/system/.hermes-gateway.service.tmp
  mv -f /etc/systemd/system/.hermes-gateway.service.tmp /etc/systemd/system/hermes-gateway.service
  install -d "$GATEWAY_DROPIN_DIR"
  sed -e "s|@CURRENT@|$HERMES_CURRENT|g" -e "s|@ENV@|$AGENT_ENV|g" -e "s|@MEM@|$mem|g" -e "s|@CPUS@|$((AGENT_CPUS * 100))%|g" \
    "$STACK_DIR/hermes/gateway-dropin.conf" > "$GATEWAY_DROPIN_DIR/10-command-center.conf"
  sed -e "s|@USER@|$OP_USER|g" -e "s|@CURRENT@|$HERMES_CURRENT|g" -e "s|@ENV@|$AGENT_ENV|g" \
    -e "s|@BIND@|${DESKTOP_BIND:-127.0.0.1}|g" -e "s|@PORT@|$DESKTOP_PORT|g" \
    "$STACK_DIR/hermes/hermes-dashboard.service" > "$DASHBOARD_UNIT"
  systemctl daemon-reload
  systemctl enable hermes-gateway.service hermes-dashboard.service >/dev/null 2>&1
}

# Traefik (container) → dashboard (host). File provider: the docker provider only sees containers.
write_route() {
  install -d -m 755 "$(dirname "$TRAEFIK_ROUTE")"
  cat > "$TRAEFIK_ROUTE.tmp" <<EOF
# Generated by hermes-host.sh units — https://$HERMES_HOST → the dashboard on the host.
http:
  routers:
    hermes:
      rule: Host(\`$HERMES_HOST\`)
      entryPoints: [websecure]
      tls:
        certResolver: cloudflare
      service: hermes
  services:
    hermes:
      loadBalancer:
        servers:
          - url: "http://${DESKTOP_BIND:-127.0.0.1}:$DESKTOP_PORT"
EOF
  chmod 644 "$TRAEFIK_ROUTE.tmp"; mv -f "$TRAEFIK_ROUTE.tmp" "$TRAEFIK_ROUTE"
}

# Traefik's packets come from the proxy bridge, not tailscale0: ufw must let them reach the
# dashboard port (harden.sh re-adds the same rule after its ufw reset).
allow_proxy_to_dashboard() {
  command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active' || return 0
  ufw allow proto tcp from "${PROXY_SUBNET:-172.20.0.0/16}" to any port "$DESKTOP_PORT" comment 'traefik → hermes dashboard (host)' >/dev/null
}

# The host-action approval gate (hermes/host-guard.py, option B): root-owned copy, consent for the
# gateway (non-TTY: exact command in Hermes' hook allowlist), and the hooks.pre_tool_call entry.
GUARD=/etc/hermes/host-guard.py
install_guard() {
  local hooks
  install -d -m 755 /etc/hermes
  install -m 755 -o root -g root "$STACK_DIR/hermes/host-guard.py" "$GUARD.tmp"
  "$GUARD.tmp" --self-test >/dev/null || { rm -f "$GUARD.tmp"; die "host-guard.py fails its self-test"; }
  mv -f "$GUARD.tmp" "$GUARD"
  runuser -u "$OP_USER" -- python3 -c '
import json, os, sys
path, cmd = sys.argv[1], sys.argv[2]
try:
    with open(path, encoding="utf-8") as f: data = json.load(f)
except FileNotFoundError: data = {}
approvals = data.setdefault("approvals", [])
if not any(a.get("event") == "pre_tool_call" and a.get("command") == cmd for a in approvals):
    approvals.append({"event": "pre_tool_call", "command": cmd})
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f: json.dump(data, f, indent=2); f.write("\n")
    os.chmod(tmp, 0o600); os.replace(tmp, path)
' "$HERMES_DATA_DIR/shell-hooks-allowlist.json" "$GUARD"
  hooks="$(agent_run python3 -c '
import json, sys, yaml
cmd = sys.argv[1]
with open("/opt/data/config.yaml", encoding="utf-8") as f: cfg = yaml.safe_load(f) or {}
entries = list(((cfg.get("hooks") or {}).get("pre_tool_call")) or [])
if not any(isinstance(e, dict) and e.get("command") == cmd for e in entries):
    entries.append({"matcher": "terminal|execute_code|write_file|patch", "command": cmd, "timeout": 10, "fail_closed": True})
    print(json.dumps(entries))
' "$GUARD")" || die "cannot read /opt/data/config.yaml"
  [ -z "$hooks" ] || agent_run hermes config set hooks.pre_tool_call "$hooks" >/dev/null
}

do_units() {
  no_symlink "$HERMES_DATA_DIR"
  if [ -L /opt/data ] || [ ! -e /opt/data ]; then ln -sfn "$HERMES_DATA_DIR" /opt/data
  else die "/opt/data exists and is not a symlink — expected a link to $HERMES_DATA_DIR"; fi
  write_agent_env
  write_units
  write_route
  allow_proxy_to_dashboard
  install_guard
  info "units, $AGENT_ENV, Traefik route, ufw rule and host-action guard written"
}

# ── activate / services ──────────────────────────────────────────────────
# activate <short> — current → <short>, previous → the old current; other complete releases pruned.
activate() {
  local short="$1" cur d
  [ -n "$(release_sha "$short")" ] || die "no complete release $short in $HERMES_RELEASES"
  cur="$(current_release)"
  if [ "$cur" != "$short" ]; then
    [ -z "$cur" ] || ln -sfn "$HERMES_RELEASES/$cur" "$HERMES_RELEASES/previous"
    ln -sfn "$HERMES_RELEASES/$short" "$HERMES_CURRENT.tmp" && mv -Tf "$HERMES_CURRENT.tmp" "$HERMES_CURRENT"
  fi
  ln -sfn "$STACK_DIR/bin/hermes" /usr/local/bin/hermes
  write_provenance "$(release_sha "$short")"
  for d in "$HERMES_RELEASES"/*/; do
    d="$(basename "$d")"
    case "$d" in "$short"|"$cur"|previous) ;; *) [ ! -e "$HERMES_RELEASES/$d/.release" ] || rm -rf "${HERMES_RELEASES:?}/$d" ;; esac
  done
  info "Hermes release: ${cur:-none} → $short"
}

services_restart() {
  systemctl restart hermes-gateway.service hermes-dashboard.service
  agent_wait_healthy 180
}

do_rollback() {
  local prev
  prev="$(basename "$(readlink -f "$HERMES_RELEASES/previous" 2>/dev/null || echo)")"
  [ -n "$prev" ] && [ -n "$(release_sha "$prev")" ] || die "no previous release kept"
  activate "$prev"
  do_units
  services_restart || warn "hermes not healthy after the rollback: journalctl -u hermes-gateway -u hermes-dashboard"
}

do_status() {
  local cur prev
  cur="$(current_release)"; prev="$(basename "$(readlink -f "$HERMES_RELEASES/previous" 2>/dev/null || echo)")"
  printf '  %-10s %s\n' release "${cur:-none}  $(release_sha "$cur")" previous "${prev:-none}"
  printf '  %-10s %s\n' gateway "$(systemctl is-active hermes-gateway 2>/dev/null || true)" dashboard "$(systemctl is-active hermes-dashboard 2>/dev/null || true)"
  if agent_healthy; then printf '  %-10s %s\n' health "ok (gateway /health + dashboard /api/status)"
  else printf '  %-10s %s\n' health "NOT OK"; fi
}

# A build (uv, npm, vite) takes GBs of RAM: run it in its own transient unit, never in the caller's
# cgroup — from a herdr pane (herdr.service MemoryMax) the OOM killer would take the terminal too.
build_in_own_unit() {
  [ "${HERMES_BUILD_UNIT:-}" = 1 ] && return 0
  command -v systemd-run >/dev/null 2>&1 || return 0
  exec systemd-run --quiet --pipe --wait --collect --unit="hermes-build-$$" \
    -p MemoryMax="${HERMES_BUILD_MEM:-8G}" -p MemorySwapMax=0 -E HERMES_BUILD_UNIT=1 \
    "$(readlink -f "$0")" build "$@"
}

cmd="${1:-}"; [ $# -gt 0 ] && shift
case "$cmd" in
  build)    build_in_own_unit "$@"; do_build "${1:-}"; echo "$BUILT_SHORT" ;;
  # A new release may ship a new unit template: regenerate it before the restart.
  activate) [ -n "${1:-}" ] || die "usage: $0 activate <sha12>"; activate "$1"; do_units; services_restart ;;
  resolve)  resolve_ref "${1:-$HERMES_REF}" ;;
  current)  current_release ;;
  rollback) do_rollback ;;
  units)    do_units ;;
  start)    systemctl start hermes-gateway.service hermes-dashboard.service; agent_wait_healthy 180 ;;
  stop)     systemctl stop hermes-dashboard.service hermes-gateway.service ;;
  restart)  services_restart ;;
  status)   do_status ;;
  releases) ls -1 "$HERMES_RELEASES" 2>/dev/null || true; echo "current: $(current_release)" ;;
  probe)    smoke_test "$HERMES_CURRENT" ;;
  healthy)  agent_healthy ;;
  -h|--help|help|"") sed -n '2,12p' "$0" ;;
  *) die "usage: $0 {build [ref]|activate <sha12>|rollback|units|start|stop|restart|status|releases|probe|healthy|resolve [ref]|current}" ;;
esac

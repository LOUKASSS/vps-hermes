  local tmp; tmp="$(mktemp /etc/hermes/.agent.env.XXXXXX)"
  cat > "$tmp" <<EOF
# Generated by hermes-host.sh units from $STACK_DIR/.env — edit .env, then: sudo command-center hermes units
HOME=/opt/data
HERMES_HOME=/opt/data
PATH=$(agent_path)
VIRTUAL_ENV=$HERMES_CURRENT/.venv
TZ=${TZ:-UTC}
LANG=C.UTF-8
PYTHONUNBUFFERED=1
PYTHONDONTWRITEBYTECODE=1
PLAYWRIGHT_BROWSERS_PATH=$HERMES_CURRENT/.playwright
HERMES_WEB_DIST=$HERMES_CURRENT/hermes_cli/web_dist
HERMES_TUI_DIR=$HERMES_CURRENT/ui-tui
HERMES_DISABLE_LAZY_INSTALLS=1
HERMES_LAZY_INSTALL_TARGET=/opt/data/lazy-packages
DISABLE_AUTOUPDATER=1
CODEX_DISABLE_UPDATE_CHECK=1
HERMES_DASHBOARD_BASIC_AUTH_USERNAME=${DESKTOP_USERNAME:-admin}
HERMES_DASHBOARD_BASIC_AUTH_PASSWORD=${DESKTOP_PASSWORD:?set by install.sh}
HERMES_DASHBOARD_BASIC_AUTH_SECRET=${DESKTOP_SECRET:?set by install.sh}
GH_CONFIG_DIR=/opt/data/home/.config/gh
